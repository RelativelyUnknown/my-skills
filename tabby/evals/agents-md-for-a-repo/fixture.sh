#!/usr/bin/env bash
# Builds the fixture project for the `agents-md-for-a-repo` case in the empty workspace.
set -euo pipefail
mkdir -p src/tinyq tests tools
cat > pyproject.toml <<'__FIXTURE_EOF__'
[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "tinyq"
version = "0.3.0"
requires-python = ">=3.12"
dependencies = []

[dependency-groups]
dev = ["pytest>=8", "ruff", "mypy"]

[tool.pytest.ini_options]
addopts = "--import-mode=importlib"
testpaths = ["tests"]

[tool.mypy]
strict = true

[tool.ruff.lint]
select = ["E", "F", "B", "UP"]
__FIXTURE_EOF__
cat > uv.lock <<'__FIXTURE_EOF__'
version = 1
requires-python = ">=3.12"
__FIXTURE_EOF__
echo "3.12" > .python-version
cat > Makefile <<'__FIXTURE_EOF__'
.PHONY: check proto
check:
	uv run ruff check src tests
	uv run mypy src
	uv run pytest -q

proto:
	uv run python tools/gen_proto.py > src/tinyq/_proto.py
__FIXTURE_EOF__
cat > tools/gen_proto.py <<'__FIXTURE_EOF__'
"""Print src/tinyq/_proto.py. Run through `make proto`; never edit the output by hand."""
print('# GENERATED by tools/gen_proto.py; do not edit. Run `make proto`.')
print('FRAME_VERSION = 2')
__FIXTURE_EOF__
cat > src/tinyq/__init__.py <<'__FIXTURE_EOF__'
"""tinyq: a tiny in-memory job queue."""
from tinyq.queue import Queue

__all__ = ["Queue"]
__FIXTURE_EOF__
cat > src/tinyq/_proto.py <<'__FIXTURE_EOF__'
# GENERATED by tools/gen_proto.py; do not edit. Run `make proto`.
FRAME_VERSION = 2
__FIXTURE_EOF__
cat > src/tinyq/queue.py <<'__FIXTURE_EOF__'
from collections import deque


class Queue:
    def __init__(self) -> None:
        self._items: deque[str] = deque()

    def push(self, item: str) -> None:
        self._items.append(item)

    def pop(self) -> str:
        return self._items.popleft()
__FIXTURE_EOF__
cat > tests/test_queue.py <<'__FIXTURE_EOF__'
from tinyq import Queue


def test_fifo():
    q = Queue()
    q.push("a")
    q.push("b")
    assert q.pop() == "a"
__FIXTURE_EOF__
git init -q -b main
git add -A
git -c user.email=eval@example.com -c user.name=eval commit -qm base
